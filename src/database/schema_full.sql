);


-- ── 5. teams_routing_rule (persiapan Teams) ───────────────────
-- Menentukan tiket mana yang dikirim ke channel Teams mana.
-- Kolom filter yang NULL = cocok dengan semua nilai.
-- Rule dengan priority_order paling kecil yang cocok dipakai duluan.
CREATE TABLE IF NOT EXISTS public.teams_routing_rule (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            TEXT NOT NULL,
  project         TEXT,
  category        TEXT,
  severity        TEXT,
  source          TEXT,
  teams_team_id   TEXT NOT NULL,
  teams_channel_id TEXT NOT NULL,
  is_active       BOOLEAN NOT NULL DEFAULT TRUE,
  priority_order  INTEGER NOT NULL DEFAULT 100,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);


-- ── 6. Row Level Security ─────────────────────────────────────
