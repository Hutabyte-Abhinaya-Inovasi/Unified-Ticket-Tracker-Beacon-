-- ── 1. intake_message ─────────────────────────────────────────
-- Semua pesan mentah dari semua channel masuk ke sini dulu.
-- Ditulis oleh: whatsappService, emailService, telegramService,
--               telegramUserListener, saveRawEmail
CREATE TABLE IF NOT EXISTS public.intake_message (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_channel  TEXT        NOT NULL DEFAULT 'wa_group',
  source_ref      TEXT,                          -- WA JID / Telegram chat_id / email id / Teams channel id
  sender          TEXT,                          -- "Nama (platform_id)"
  thread_ref      TEXT,                          -- ID pesan yang di-reply/quote
  received_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  body_text       TEXT,
  attachments     JSONB,
  raw_payload     JSONB,                         -- group_name, candidate_sent, candidate_tg_msg_id, dll
  idempotency_key TEXT,                          -- ID pesan unik dari platform
  status          TEXT        NOT NULL DEFAULT 'pending',
  ticket_id       TEXT,                          -- link ke Unified_Ticket_Tracker.ticket_id
  processed_at    TIMESTAMPTZ,
  ignore_reason   TEXT,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT intake_message_source_channel_check
    CHECK (source_channel IN ('wa_group', 'wa_dm', 'telegram', 'email', 'teams')),
  CONSTRAINT intake_message_status_check
    CHECK (status IN ('pending', 'processed', 'threaded', 'ignored'))
);

-- saveRawIntakeMessage() mengandalkan error 23505 (unique violation)
-- untuk melewati pesan duplikat → WAJIB unique.
CREATE UNIQUE INDEX IF NOT EXISTS uq_intake_idempotency_key
  ON public.intake_message (idempotency_key)
  WHERE idempotency_key IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_intake_status
  ON public.intake_message (status);
CREATE INDEX IF NOT EXISTS idx_intake_source_ref_status
  ON public.intake_message (source_ref, status);
CREATE INDEX IF NOT EXISTS idx_intake_ticket_id
  ON public.intake_message (ticket_id);


-- ── 2. Unified_Ticket_Tracker ─────────────────────────────────
-- Tabel tiket utama.
CREATE TABLE IF NOT EXISTS public."Unified_Ticket_Tracker" (
  id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- dipakai /ai [2389] (internal id)
  ticket_id             TEXT        NOT NULL UNIQUE,                         -- TCK-YYYYMMDD-XXXX

  -- Isi tiket
  email_id              TEXT,                    -- message id asal (dipakai threading via quote)
  "from"                TEXT,
  subject               TEXT,
  body                  TEXT,
  summary               TEXT,
  category              TEXT DEFAULT 'Incident Management',
  project               TEXT,
  priority              TEXT DEFAULT 'MEDIUM',
  severity              TEXT,
  source                TEXT,                    -- whatsapp / wa_group / telegram / telegram_personal / telegram_manual / email / teams
  group_id              TEXT,
  assignee              TEXT,                    -- dipakai filter query_tickets (AI)
  action_needed         TEXT,                    -- dipakai filter query_tickets (AI)
  requester             TEXT,                    -- input manual /tiket
  reported_time         TEXT,                    -- input manual /tiket
  issue_type            TEXT,                    -- input manual /tiket

  -- Status & waktu
  status                TEXT NOT NULL DEFAULT 'Draft',
    -- Draft | Pending Confirmation | In Progress | Escalated |
    -- Done | Resolved | Cancelled | No Action | Logged (No Action)
  processed_at          TIMESTAMPTZ DEFAULT now(),
  updated_at            TIMESTAMPTZ DEFAULT now(),
  last_message_at       TIMESTAMPTZ,
  created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),

  -- Telegram
  telegram_sent         BOOLEAN DEFAULT FALSE,
  telegram_message_id   TEXT,
  telegram_chat_id      TEXT,

  -- SLA Konfirmasi (looping 1)
  intake_received_at    TIMESTAMPTZ,
  sla_confirm_warned    BOOLEAN NOT NULL DEFAULT FALSE,
  sla_confirm_alerted   BOOLEAN NOT NULL DEFAULT FALSE,
  confirmed_at          TIMESTAMPTZ,
  confirmed_by          TEXT,
  rejected_at           TIMESTAMPTZ,
  rejected_by           TEXT,

  -- SLA Pekerjaan (looping 2)
  sla_deadline_minutes  INTEGER,
  sla_warned            BOOLEAN NOT NULL DEFAULT FALSE,
  sla_alerted           BOOLEAN NOT NULL DEFAULT FALSE,
  escalated_at          TIMESTAMPTZ,
  resolved_at           TIMESTAMPTZ,
  resolved_by           TEXT,

  -- ClickUp
  clickup_task_id       TEXT,
  clickup_url           TEXT,

  -- Microsoft Teams (persiapan kirim tiket ke Teams)
  teams_sent            BOOLEAN NOT NULL DEFAULT FALSE,
  teams_team_id         TEXT,
  teams_channel_id      TEXT,
  teams_message_id      TEXT,                    -- untuk reply/update thread di Teams
  teams_web_url         TEXT,
  teams_sent_at         TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_utt_group_id_status
  ON public."Unified_Ticket_Tracker" (group_id, status);
CREATE INDEX IF NOT EXISTS idx_utt_status
  ON public."Unified_Ticket_Tracker" (status);
CREATE INDEX IF NOT EXISTS idx_utt_processed_at
  ON public."Unified_Ticket_Tracker" (processed_at DESC);
CREATE INDEX IF NOT EXISTS idx_utt_email_id
  ON public."Unified_Ticket_Tracker" (email_id);
CREATE INDEX IF NOT EXISTS idx_utt_telegram_message_id
  ON public."Unified_Ticket_Tracker" (telegram_message_id);

-- Query SLA worker
CREATE INDEX IF NOT EXISTS idx_utt_sla
  ON public."Unified_Ticket_Tracker" (status, confirmed_at)
  WHERE status = 'In Progress' AND confirmed_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_utt_sla_confirmation
  ON public."Unified_Ticket_Tracker" (status, intake_received_at)
  WHERE status = 'Pending Confirmation' AND intake_received_at IS NOT NULL;

-- Tiket yang belum terkirim ke Teams
CREATE INDEX IF NOT EXISTS idx_utt_teams_pending
  ON public."Unified_Ticket_Tracker" (teams_sent)
  WHERE teams_sent = FALSE;


-- ── 3. conversation ───────────────────────────────────────────
-- Sesi percakapan per grup (dipakai threading lama + close saat Done).
CREATE TABLE IF NOT EXISTS public.conversation (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_key  TEXT NOT NULL UNIQUE,        -- "<source>_<groupId>", dipakai upsert onConflict
  ticket_id         TEXT,
  source_channel    TEXT,
  group_id          TEXT,
  status            TEXT NOT NULL DEFAULT 'OPEN', -- OPEN | CLOSED
  last_message      TEXT,
  last_message_at   TIMESTAMPTZ,
  summary           TEXT,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_conversation_ticket_id
  ON public.conversation (ticket_id);


-- ── 4. whatsapp_auth ──────────────────────────────────────────
-- Session Baileys disimpan di Supabase (supabaseAuthState.js).
